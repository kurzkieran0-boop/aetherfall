"""Build ../videos_package.zip: kit + per-video sources, shots.json, narration (FLAC) + word timestamps, test stills,
run_all.ps1, README.txt.  No rendered frames, clips, blends, voices or regenerable assets (kept small)."""
import json, sys, zipfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import KIT, VIDEOS, SLUGS_ALL

OUT = VIDEOS.parent / "videos_package.zip"
KEEP_BUILD = {"timeline.json", "voice.flac", "tts_state.json"}


def main():
    files = []
    for p in sorted(KIT.rglob("*")):
        rel = p.relative_to(VIDEOS)
        parts = rel.parts
        if p.is_dir() or "__pycache__" in parts or "voices" in parts or p.suffix in (".lock", ".tmp"):
            continue
        if parts[:3] in (("kit", "assets", "tex"), ("kit", "assets", "digits")):
            continue      # regenerated by kit/art.py
        files.append(p)
    for slug in SLUGS_ALL:
        v = VIDEOS / slug
        for n in ("config.py", "story.py", "scene.py", "shots.json", "script.txt"):
            if (v / n).exists():
                files.append(v / n)
        for n in KEEP_BUILD:
            if (v / "build" / n).exists():
                files.append(v / "build" / n)
        files += sorted((v / "build" / "test_still").glob("*.png"))
    for n in ("run_all.ps1", "README.txt"):
        files.append(VIDEOS / n)
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in files:
            z.write(p, Path("videos") / p.relative_to(VIDEOS))
    print(f"{OUT}: {len(files)} files, {OUT.stat().st_size / 2 ** 20:.1f} MB")


if __name__ == "__main__":
    main()
